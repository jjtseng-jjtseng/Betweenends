"""Generate docs/COVERAGE.md and docs/TRENDS.md from data/processed/.

    python -m pipeline.report [--as-of YYYY-MM-DD]

Every number in those documents is computed from the processed tables - nothing is typed
in by hand - so re-running after a data refresh keeps the docs truthful.
"""
from __future__ import annotations

import argparse
import datetime as dt
from pathlib import Path

import pandas as pd

from . import config

NATIONAL = ["indoor_nationals", "joad_indoor_nationals", "target_nationals", "joad_target_nationals",
            "collegiate_target_nationals", "collegiate_3d_nationals", "field_nationals", "3d_nationals", "oas_nationals"]


def md_table(df: pd.DataFrame, floatfmt: str = "{:,.3f}") -> str:
    if df.empty:
        return "_(none)_"
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, float):
                cells.append("" if pd.isna(v) else (f"{int(v):,}" if float(v).is_integer() and abs(v) > 99 else floatfmt.format(v)))
            elif isinstance(v, (int,)) and not isinstance(v, bool):
                cells.append(f"{v:,}")
            else:
                cells.append(str(v).replace("|", "/"))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def build(proc: Path, docs: Path, as_of: dt.date) -> None:
    docs.mkdir(parents=True, exist_ok=True)
    t = pd.read_csv(proc / "tournaments.csv.gz", dtype={"usat_leg": str})
    ev = pd.read_csv(proc / "events.csv.gz")
    en = pd.read_csv(proc / "entries.csv.gz", low_memory=False, dtype={"alt_id": str})
    ar = pd.read_csv(proc / "archers.csv.gz", low_memory=False)
    mr = pd.read_csv(proc / "marquee_results.csv.gz", low_memory=False)
    lt = pd.read_csv(proc / "legacy_tournaments.csv") if (proc / "legacy_tournaments.csv").exists() else pd.DataFrame()
    le = pd.read_csv(proc / "legacy_entries.csv.gz", low_memory=False) if (proc / "legacy_entries.csv.gz").exists() else pd.DataFrame()

    scoped = t[t.in_scope]
    can = en[en.is_canonical]
    # ---------------------------------------------------------------- COVERAGE
    L = [f"# Coverage (data as of {as_of})", "",
         "Generated by `python -m pipeline.report` from `data/processed/`. See `docs/METHODOLOGY.md` for how scope is defined.", "",
         "## Headline numbers", "",
         f"- Tournaments in the Between Ends index: **{len(t):,}** ({t.start_date.min()} to {t.start_date.max()}); "
         f"in scope and collected: **{len(scoped):,}**; scheduled-but-not-yet-held (catalogued only): **{int((t.status == 'upcoming').sum()):,}**",
         f"- Events collected: **{len(ev):,}** ({', '.join(f'{k}: {v:,}' for k, v in ev.event_type.value_counts().items())})",
         f"- Result entries: **{len(en):,}**, of which **{len(can):,}** are canonical performances "
         f"(the other {len(en) - len(can):,} are the same performance re-published in a Combined-results event)",
         f"- Distinct archers (Between Ends era): **{en.archer_id.nunique():,}**; "
         f"with 2016-17 USA Archery PDF results included: **{len(ar):,}**",
         f"- Arrow-by-arrow records: **{int((en.arrows_shot > 0).sum()):,}** entries",
         f"- Pre-2018 legacy rows (usarchery.org PDFs): **{len(le):,}** from **{int(lt.parsed.sum()) if len(lt) else 0}** parsed documents", "",
         "## Tournaments in scope, by category and year (championship season)", ""]
    sc = scoped.copy()
    sc["season"] = sc.championship_year.fillna(sc.year).astype(int)
    pv = sc.pivot_table(index="category", columns="season", values="tournament_id", aggfunc="count", fill_value=0)
    pv["total"] = pv.sum(axis=1)
    pv = pv.sort_values("total", ascending=False).reset_index()
    pv.columns = [str(c) for c in pv.columns]
    L += [md_table(pv), "", "## Nationals + USAT + trials: archers per championship", ""]
    mq = can.merge(t[["tournament_id", "category", "championship_key", "is_marquee"]], on="tournament_id")
    mq = mq[mq.is_marquee & mq.championship_key.notna() & ~mq.is_guest]
    g = (mq.groupby("championship_key").agg(tournaments=("tournament_id", "nunique"), entries=("entry_id", "size"), archers=("archer_id", "nunique"))
           .reset_index())
    g["category"] = g.championship_key.str.split(":").str[0]
    g["season"] = g.championship_key.str.split(":").str[1]
    g = g.sort_values(["category", "season"])[["category", "season", "tournaments", "entries", "archers"]]
    L += [md_table(g), ""]

    L += ["## Known gaps and caveats", "",
          "- **Between Ends starts in December 2017.** Marquee results for 2016 and 2017 come from USA Archery's own PDF results books "
          "(`pipeline/legacy.py`); the documents that could not be parsed are listed below. Those rows carry **no arrow-level data** and no stable member id "
          "(archers are linked to Between Ends histories only when the exact name is unambiguous).",
          "- **COVID-19**: no Field Nationals or Collegiate Nationals in 2020, and the 2020 JOAD Target Nationals did not run; these are real absences, not collection gaps.",
          "- **2016 Target Nationals** are not listed on USA Archery's public results-archive page (only the 2017 NTC/JNC book is), so that championship is absent.",
          "- **Events with registered archers but no scores** exist at the source (organisers created the event but never entered arrows). They are kept, flagged `has_scores = False`.",
          "- **Typed-in round totals** that exceed what the event's declared format can produce are flagged `score_exceeds_format` and excluded from statistics.",
          "- **Elimination placings** (`match_rows.final_place`) are inferred for single-elimination brackets only and are reliable only for finished events.", ""]
    if len(lt):
        bad = lt[~lt.parsed.fillna(False).astype(bool)][["source_slug", "category", "unparsed_reason"]]
        L += ["### USA Archery documents catalogued but not parsed", "", md_table(bad), ""]
        good = lt[lt.parsed.fillna(False).astype(bool)][["source_slug", "category", "start_date", "n_rows", "n_rows_rejected", "n_sum_check_failed"]]
        L += ["### Parsed USA Archery documents", "", md_table(good), ""]
    (docs / "COVERAGE.md").write_text("\n".join(L) + "\n")

    # ------------------------------------------------------------------ TRENDS
    T = [f"# What the data says (as of {as_of})", "",
         "Generated by `python -m pipeline.report`. Descriptive statistics over canonical performances, guests excluded. "
         "`level` = mean share of the maximum possible score on complete cards.", ""]
    # participation over time for the big national championships
    part = g.copy()
    part["season"] = part.season.astype(int)
    for cat, label in (("indoor_nationals", "Indoor Nationals"), ("target_nationals", "Target Nationals / U.S. Open"),
                       ("usat_series", "USAT series (all legs combined)"), ("field_nationals", "Field Nationals"),
                       ("joad_indoor_nationals", "JOAD Indoor Nationals"), ("joad_target_nationals", "JOAD Target Nationals")):
        s = part[part.category == cat][["season", "tournaments", "entries", "archers"]]
        if len(s):
            T += [f"## {label}: participation by season", "", md_table(s), ""]
    # scoring level by season for the senior open divisions at indoor + target nationals
    cc = mq[mq.complete_card & (mq.age_class == "Senior") & mq.category.isin(["indoor_nationals", "target_nationals"])].copy()
    cc = cc.merge(t[["tournament_id", "championship_year"]], on="tournament_id")
    if len(cc):
        lv = (cc.groupby(["category", "division", "gender", "championship_year"]).agg(archers=("archer_id", "nunique"), level=("pct_of_max", "mean"),
                                                                                        best=("pct_of_max", "max")).reset_index())
        lv = lv[lv.division.isin(["Recurve", "Compound", "Barebow"]) & lv.gender.isin(["M", "W"]) & (lv.archers >= 8)]
        for cat, label in (("indoor_nationals", "Indoor Nationals"), ("target_nationals", "Target Nationals")):
            p = lv[lv.category == cat].pivot_table(index="championship_year", columns=["division", "gender"], values="level")
            if len(p):
                p.columns = [f"{a} {b}" for a, b in p.columns]
                T += [f"## {label}: senior level over time (mean % of maximum score)", "", md_table(p.reset_index().rename(columns={"championship_year": "season"}), "{:.3f}"), ""]
    # most decorated
    top = ar.sort_values(["n_national_championships", "n_marquee_tournaments"], ascending=False).head(25)[
        ["display_name", "primary_division", "gender", "first_date", "last_date", "n_national_championships", "n_usat_events", "n_marquee_tournaments"]]
    T += ["## Most frequent national-championship competitors (all eras)", "", md_table(top), ""]
    tr = pd.read_csv(proc / "archer_trends.csv.gz")
    tr = tr[tr.n_performances >= 5]
    cnt = tr.trend.value_counts()
    T += ["## Archer trajectories (>= 5 comparable performances)", "",
          md_table(cnt.rename_axis("trend").reset_index(name="archer-division series")), "",
          "Trend label: OLS slope of points-per-arrow on time; `improving`/`declining` need |slope / SE| >= 2, otherwise `stable`.", ""]
    imp = tr[tr.trend == "improving"].merge(ar[["archer_id", "display_name"]], on="archer_id").sort_values("slope_per_year", ascending=False).head(15)
    T += ["### Fastest improvers (points per arrow per year)", "",
          md_table(imp[["display_name", "division", "format_family", "n_performances", "span_years", "first_avg_arrow", "last_avg_arrow", "slope_per_year"]]), ""]
    (docs / "TRENDS.md").write_text("\n".join(T) + "\n")
    print(f"wrote {docs / 'COVERAGE.md'} and {docs / 'TRENDS.md'}")


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="pipeline.report", description=__doc__)
    p.add_argument("--as-of", type=dt.date.fromisoformat, default=dt.date.today())
    p.add_argument("--dir", type=Path, default=config.PROCESSED_DIR)
    p.add_argument("--docs", type=Path, default=config.REPO_ROOT / "docs")
    a = p.parse_args(argv)
    build(a.dir, a.docs, a.as_of)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
